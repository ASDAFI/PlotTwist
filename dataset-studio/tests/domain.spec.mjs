import assert from 'node:assert/strict';
import {demoItems,parseResponse,resolveResponseKey,clampBox,validateBox,exportRecord,safePath,zipFiles} from '../lib/dataset.ts';
const samples=demoItems();
assert.equal(parseResponse('<reasoning>x</reasoning><answer> A </answer>').answer,'A');
assert.equal(parseResponse('<answer>Person A</answer>').answer,'Person A');
assert.equal(parseResponse('<answer>A</answer><answer>B</answer>').malformed,true);
assert.equal(parseResponse('A').malformed,true);
assert.equal(resolveResponseKey(samples,'images/020.jpg'),'020.json');
assert.equal(resolveResponseKey(samples,'020'),'020.json');
assert.equal(resolveResponseKey(samples,'20'),null,'Leading zeros must not be removed');
const shared={...samples[0],key:'other-question.json'};
assert.equal(resolveResponseKey([...samples,shared],'images/020.jpg'),null,'One image linked to two questions must be ambiguous');
assert.equal(resolveResponseKey([...samples,shared],'json/020.json'),'020.json','An exact record path disambiguates');
const unknown=structuredClone(samples[0]);
unknown.data.extra={a:[1,null,'A']};
unknown.data.answer.extra={untouched:true};
unknown.data.ordered_deceptions[2].bounding_boxes[0].extra='keep';
const unchanged=exportRecord(unknown,'Reviewer','~Reviewer1');
assert.deepEqual(unchanged,unknown.data);
unknown.changed=true;
const edited=exportRecord(unknown,'Reviewer','~Reviewer1');
assert.equal(edited.contributor.name,'Reviewer');
assert.equal(edited.answer.option,'A');
assert.deepEqual(edited.extra,unknown.data.extra);
assert.equal(edited.ordered_deceptions[2].bounding_boxes[0].x,780.9638886101253);
assert.equal(edited.ordered_deceptions[2].bounding_boxes[0].extra,'keep');
assert.equal(edited.answer.extra.untouched,true);
assert.equal(unknown.data.contributor.name,'mahyar','Export must not mutate source state');
const moved=clampBox({box_id:'x',x:1000,y:-9,width:100,height:60},1013,675);
assert.deepEqual(moved,{box_id:'x',x:913,y:0,width:100,height:60});
assert.equal(validateBox(moved,1013,675),true);
for(const p of ['../x','/x','images/../../x','C:\\secret','a//b'])assert.throws(()=>safePath(p));
const zip=zipFiles([{path:'review/json/نمونه.json',bytes:new TextEncoder().encode(JSON.stringify(edited))}]);
assert.equal(new DataView(zip.buffer).getUint32(0,true),0x04034b50);
assert.ok(zip.length>100);
console.log('Domain checks passed: identity mapping, ambiguity, literal answers, metadata preservation, coordinates, path containment, and ZIP generation.');
